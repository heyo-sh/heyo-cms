export interface SlugCandidate {
  id: string;
  /** The locale the slug matched in; null for a field that is not localized. */
  locale: string | null;
  current: boolean;
}

/**
 * Every document a slug points at, best match first: a current address in
 * the requested locale, then in another locale, then a previous address in
 * the requested locale, then in another.
 *
 * Trashed documents are left out — a trashed page has no address — and so
 * is anything that is not a slug at all, before a query is spent on it.
 */
export async function slugCandidates(options: {
  db: ScopedDb;
  collection: ResolvedCollection;
  field: string;
  slug: string;
  locale: string | null;
  locales: string[];
}): Promise<SlugCandidate[]> {
  const { db, collection, field, slug } = options;
  const definition = collection.fields[field];
  if (!definition || !isSlug(slug)) return [];

  const localized = definition.localized;
  const current: SlugCandidate[] = [];
  const rows: Row[] = await db.query({
    table: documentsTableName,
    where: and(
      eq("collection", collection.slug),
      eq("deleted_at", null),
      localized
        ? or(...options.locales.map((locale) => eq(`${field}.${locale}`, slug)))
        : eq(field, slug),
    ),
    limit: 20,
  });
  for (const row of rows) {
    const value = asObject(row.data)[field];
    if (!localized) {
      current.push({ id: String(row.id), locale: null, current: true });
      continue;
    }
    for (const locale of options.locales) {
      if (asObject(value)[locale] === slug) {
        current.push({ id: String(row.id), locale, current: true });
      }
    }
  }

  const previous: SlugCandidate[] = [];
  if (slugOptions(definition).history === true) {
    const history = await db.find(
      slugHistoryTable,
      and(
        eq("collection", collection.name),
        eq("field", field),
        eq("slug", slug),
      ),
    );
    const alive = await liveIds(
      db,
      collection,
      history.map((row) => String(row.document_id)),
    );
    for (const row of history) {
      const id = String(row.document_id);
      if (!alive.has(id)) continue;
      const locale = String(row.locale ?? "");
      previous.push({ id, locale: locale === "" ? null : locale, current: false }); // prettier-ignore
    }
  }

  const rank = (candidate: SlugCandidate) =>
    candidate.locale === null || candidate.locale === options.locale ? 0 : 1;
  return [
    ...current.sort((a, b) => rank(a) - rank(b)),
    ...previous.sort((a, b) => rank(a) - rank(b)),
  ];
}

async function liveIds(
  db: ScopedDb,
  collection: ResolvedCollection,
  ids: string[],
): Promise<Set<string>> {
  if (ids.length === 0) return new Set();
  const rows = await db.query({
    table: documentsTableName,
    where: and(
      eq("collection", collection.slug),
      eq("deleted_at", null),
      inList("id", [...new Set(ids)]),
    ),
  });
  return new Set(rows.map((row) => String(row.id)));
}

export interface PreviousSlugRow {
  slug: string;
  field: string;
  locale: string | null;
  createdAt: string | null;
}

export async function previousSlugRows(options: {
  db: ScopedDb;
  collection: ResolvedCollection;
  documentId: string;
  field?: string;
  locale?: string | null;
}): Promise<PreviousSlugRow[]> {
  const conditions: Where[] = [
    eq("collection", options.collection.name),
    eq("document_id", options.documentId),
  ];
  if (options.field !== undefined) conditions.push(eq("field", options.field));
  if (options.locale !== undefined) {
    conditions.push(eq("locale", options.locale ?? ""));
  }
  const rows = await options.db.find(slugHistoryTable, and(...conditions));
  return rows
    .map((row) => ({
      slug: String(row.slug),
      field: String(row.field),
      locale: row.locale ? String(row.locale) : null,
      createdAt: toIso(row.created_at),
    }))
    .sort(
      (a, b) =>
        (b.createdAt ?? "").localeCompare(a.createdAt ?? "") ||
        a.slug.localeCompare(b.slug),
    );
}
