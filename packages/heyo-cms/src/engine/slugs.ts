/**
 * The `slug` field's behaviour: made from another field when empty, cleaned
 * when typed, unique where it has to be, and remembered when it changes.
 *
 * Here rather than in a hook because every one of those has to happen on
 * every write path — the panel, the REST API, an import, a scheduled change,
 * a script — and a hook is something a project can forget to register.
 *
 * The history lives in its own table, `slug_history`, one row per previous
 * address: a real column with a unique index answers "who owned this URL"
 * in one lookup on every engine, where a list inside the document body would
 * be a `LIKE` over every row of the collection.
 */

export const slugHistoryTable = "slug_history";

/** Free suffixes tried before giving up: `title`, `title-2` … `title-50`. */
const maxSuffix = 50;

export interface SlugFieldOptions {
  from?: string;
  history?: boolean;
  unique?: boolean;
  maxLength?: number;
  slugify?: (text: string) => string;
}

/** The field's own `slugify`, or the built-in one at its `maxLength`. */
export function slugCleaner(field: FieldDefinition): (text: string) => string {
  const settings = slugOptions(field);
  if (typeof settings.slugify === "function") return settings.slugify;
  const max = settings.maxLength;
  return (text) => slugify(text, max === undefined ? {} : { maxLength: max });
}

export function slugFields(
  collection: ResolvedCollection,
): [string, FieldDefinition][] {
  return Object.entries(collection.fields).filter(
    ([, field]) => field.type === "slug",
  );
}

export function slugOptions(field: FieldDefinition): SlugFieldOptions {
  return field.options as SlugFieldOptions;
}

/** One slug that stopped being a document's address in a write. */
export interface SlugMove {
  field: string;
  /** Empty for a field that is not localized, like `media_usages`. */
  locale: string;
  from: string;
  to: string;
}

export interface PrepareSlugsOptions {
  db: ScopedDb;
  collection: ResolvedCollection;
  /** What the write asks for, after the `before` hooks. */
  input: JsonObject;
  /** The stored body before this write; null for a create. */
  stored: JsonObject | null;
  locale: string;
  /** Null for a create whose id is not known to the caller yet. */
  documentId: string | null;
}

/**
 * Fills in, cleans and checks every slug field a write touches.
 *
 * Returns the input with the slugs settled and the moves the write implies,
 * which `recordSlugMoves` writes once the document row exists.
 */
export async function prepareSlugs(
  options: PrepareSlugsOptions,
): Promise<{ input: JsonObject; moves: SlugMove[] }> {
  const fields = slugFields(options.collection);
  if (fields.length === 0) return { input: options.input, moves: [] };

  const input = { ...options.input };
  const moves: SlugMove[] = [];

  for (const [name, field] of fields) {
    const settings = slugOptions(field);
    const locale = field.localized ? options.locale : "";
    const current = ownValue(options.stored, name, field, options.locale);
    const given = input[name];
    const clean = slugCleaner(field);

    let next: string | null | undefined;
    if (typeof given === "string" && given.trim() !== "") {
      next = clean(given);
      if (next === "") {
        throw CmsError.validation(
          `${options.collection.name}.${name}: "${given}" has no letters or digits to make a slug from`,
        );
      }
      if (settings.unique !== false) {
        await assertFree({ ...options, field: name, locale, slug: next });
      }
    } else if (
      given === null ||
      given === "" ||
      (given === undefined && current === null)
    ) {
      // Empty: made from its source, once. A slug that already exists is
      // never regenerated by an edit of the title — renaming a page must not
      // move its URL — only by somebody clearing it on purpose.
      const source =
        settings.from === undefined
          ? null
          : sourceValue(options, settings.from);
      const base = source === null ? "" : clean(source);
      if (base !== "") {
        next =
          settings.unique === false
            ? base
            : await firstFree({ ...options, field: name, locale, base });
      } else if (given !== undefined) {
        next = null;
      }
    }

    if (next === undefined) continue;
    input[name] = next;
    if (
      settings.history === true &&
      current !== null &&
      next !== null &&
      next !== current
    ) {
      moves.push({ field: name, locale, from: current, to: next });
    }
  }

  return { input, moves };
}

/**
 * Writes what `prepareSlugs` decided, inside the same transaction.
 *
 * The old slug becomes a previous address of the document; a slug the
 * document moves back to stops being one, so an address is never both.
 */
export async function recordSlugMoves(
  db: ScopedDb,
  collection: ResolvedCollection,
  documentId: string,
  moves: SlugMove[],
  now: Date,
): Promise<void> {
  for (const move of moves) {
    const scope = and(
      eq("collection", collection.name),
      eq("field", move.field),
      eq("locale", move.locale),
    );
    await db.delete(
      slugHistoryTable,
      and(scope, eq("document_id", documentId), eq("slug", move.to)),
    );
    const existing = await db.findOne(
      slugHistoryTable,
      and(scope, eq("slug", move.from)),
    );
    if (existing) continue;
    await db.insert(slugHistoryTable, {
      id: createId("slg"),
      collection: collection.name,
      field: move.field,
      locale: move.locale,
      slug: move.from,
      document_id: documentId,
      created_at: now,
    });
  }
}

export async function removePreviousSlugRow(
  db: ScopedDb,
  collection: ResolvedCollection,
  documentId: string,
  field: string,
  locale: string,
  slug: string,
): Promise<void> {
  await db.delete(
    slugHistoryTable,
    and(
      eq("collection", collection.name),
      eq("document_id", documentId),
      eq("field", field),
      eq("locale", locale),
      eq("slug", slug),
    ),
  );
}

/** Every previous address of one document goes when the document does. */
export async function releaseSlugs(
  db: ScopedDb,
  collection: ResolvedCollection,
  documentId: string,
): Promise<void> {
  await db.delete(
    slugHistoryTable,
    and(eq("collection", collection.name), eq("document_id", documentId)),
  );
}

interface SlugScope {
  db: ScopedDb;
  collection: ResolvedCollection;
  documentId: string | null;
  field: string;
  /** Empty for a field that is not localized. */
  locale: string;
}

/** Whether this scope's field keeps history, so `slug_history` exists for it. */
function hasHistory(scope: SlugScope): boolean {
  const field = scope.collection.fields[scope.field];
  return field !== undefined && slugOptions(field).history === true;
}

/**
 * Refuses a slug another document uses, as its address or as a previous one.
 *
 * Trashed documents count: restoring a page must never bring back a URL
 * somebody else has taken since. A previous address is not taken over
 * silently either — it is a redirect somebody relies on — so the message
 * says where it leads and how to free it.
 */
export async function assertFree(
  scope: SlugScope & { slug: string },
): Promise<void> {
  const where = scope.locale ? ` in "${scope.locale}"` : "";
  const owner = await currentOwner(scope, scope.slug);
  if (owner !== null) {
    throw CmsError.conflict(
      `The slug "${scope.slug}" is already used${where} by another document of ${scope.collection.label} (${owner}).`,
    );
  }
  const previous = await historyOwner(scope, scope.slug);
  if (previous !== null) {
    throw CmsError.conflict(
      `The slug "${scope.slug}" is a previous slug of another document of ${scope.collection.label} (${previous})${where} and redirects there. Remove it from that document's previous slugs first.`,
    );
  }
}

async function firstFree(scope: SlugScope & { base: string }): Promise<string> {
  for (let n = 1; n <= maxSuffix; n += 1) {
    const candidate = n === 1 ? scope.base : `${scope.base}-${n}`;
    if (
      (await currentOwner(scope, candidate)) === null &&
      (await historyOwner(scope, candidate)) === null
    ) {
      return candidate;
    }
  }
  throw CmsError.conflict(
    `No free slug for "${scope.base}" after ${maxSuffix} tries; set one explicitly.`,
  );
}

/** The other document whose current slug this is, if any. */
async function currentOwner(
  scope: SlugScope,
  slug: string,
): Promise<string | null> {
  const path = scope.locale ? `${scope.field}.${scope.locale}` : scope.field;
  const rows = await scope.db.query({
    table: documentsTableName,
    where: and(
      eq("collection", scope.collection.slug),
      eq(path, slug),
      ...(scope.documentId === null ? [] : [ne("id", scope.documentId)]),
    ),
    limit: 1,
  });
  return rows[0] ? String(rows[0].id) : null;
}

/** The other document this slug used to belong to, if any. */
async function historyOwner(
  scope: SlugScope,
  slug: string,
): Promise<string | null> {
  if (!hasHistory(scope)) return null;
  const row = await scope.db.findOne(
    slugHistoryTable,
    and(
      eq("collection", scope.collection.name),
      eq("field", scope.field),
      eq("locale", scope.locale),
      eq("slug", slug),
      ...(scope.documentId === null ? [] : [ne("document_id", scope.documentId)]), // prettier-ignore
    ),
  );
  return row ? String(row.document_id) : null;
}

/**
 * A field's value as stored for this locale, ignoring any fallback.
 *
 * Only the locale's own value counts: a Polish translation without a slug
 * of its own does not "have" the English one, and treating the fallback as
 * its slug would stop one from ever being generated.
 */
function ownValue(
  stored: JsonObject | null,
  name: string,
  field: FieldDefinition,
  locale: string,
): string | null {
  if (!stored) return null;
  const value = field.localized ? asObject(stored[name])[locale] : stored[name];
  return typeof value === "string" && value !== "" ? value : null;
}

/** The text a slug is made from: this write's value, or the stored one. */
function sourceValue(
  options: PrepareSlugsOptions,
  from: string,
): string | null {
  const field = options.collection.fields[from];
  if (!field) return null;
  const given = options.input[from];
  const value =
    given !== undefined
      ? given
      : field.localized
        ? (asObject(options.stored?.[from])[options.locale] ?? null)
        : (options.stored?.[from] ?? null);
  return typeof value === "string" && value.trim() !== "" ? value : null;
}

